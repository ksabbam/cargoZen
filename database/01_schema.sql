CREATE TABLE IF NOT EXISTS ROLES (
    ROLE_ID         NUMBER AUTOINCREMENT PRIMARY KEY,
    ROLE_NAME       VARCHAR(50)  NOT NULL UNIQUE,
    DESCRIPTION     VARCHAR(255),
    IS_ACTIVE       BOOLEAN DEFAULT TRUE,
