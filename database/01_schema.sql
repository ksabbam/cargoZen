-- =============================================================
-- VIEWS for common lookups
-- =============================================================
USE SCHEMA ADMIN;

CREATE OR REPLACE VIEW V_ORGANIZATION_LOOKUP AS
SELECT ORG_ID AS ID, ORG_CODE AS CODE, ORG_NAME AS NAME, ORG_TYPE AS TYPE,
       IS_CUSTOMER, IS_VENDOR, IS_AGENT, IS_CARRIER, COUNTRY
FROM ORGANIZATIONS WHERE IS_ACTIVE = TRUE AND APPROVAL_STATUS = 'APPROVED';

CREATE OR REPLACE VIEW V_AIRLINE_LOOKUP AS
SELECT AIRLINE_ID AS ID, AIRLINE_CODE AS CODE, AIRLINE_NAME AS NAME,
       IATA_CODE, COUNTRY
FROM AIRLINES WHERE IS_ACTIVE = TRUE;

CREATE OR REPLACE VIEW V_SHIPPING_LINE_LOOKUP AS
SELECT LINE_ID AS ID, LINE_CODE AS CODE, LINE_NAME AS NAME,
       SCAC_CODE, COUNTRY
FROM SHIPPING_LINES WHERE IS_ACTIVE = TRUE;

CREATE OR REPLACE VIEW V_ACCOUNT_LOOKUP AS
SELECT ACCOUNT_ID AS ID, ACCOUNT_CODE AS CODE, ACCOUNT_NAME AS NAME,
       ACCOUNT_TYPE, ACCOUNT_SUBTYPE
FROM ACCOUNTS WHERE IS_ACTIVE = TRUE;

CREATE OR REPLACE VIEW V_CHARGE_LOOKUP AS
SELECT CHARGE_ID AS ID, CHARGE_CODE AS CODE, CHARGE_NAME AS NAME,
       CHARGE_TYPE, CHARGE_CATEGORY, APPLICABLE_FOR
FROM CHARGE_MASTER WHERE IS_ACTIVE = TRUE;
